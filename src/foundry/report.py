"""Foundry evaluation report generation — Markdown and JSON output."""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List

from .client import EvalRunResult
from .config import CloudEvalConfig


def generate_foundry_report(
    result: EvalRunResult,
    config: CloudEvalConfig,
    output_dir: Path,
) -> None:
    """Generate evaluation report in configured formats.

    Args:
        result: The completed Foundry eval run result.
        config: The Foundry configuration.
        output_dir: Where to write report files.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    formats = config.output.formats

    if "markdown" in formats:
        md_path = output_dir / "report.md"
        _generate_markdown(result, config, md_path)
        print(f"  ✓ Markdown report: {md_path}")

    if "json" in formats:
        json_path = output_dir / "results.json"
        _generate_json(result, config, json_path)
        print(f"  ✓ JSON results: {json_path}")


def _summarize_scores(output_items: List[Dict[str, Any]]) -> Dict[str, Dict[str, float]]:
    """Summarize scores from output items by grader name.

    Handles both API formats:
    - List format (live API): results = [{name, score, passed, ...}, ...]
    - Dict format (legacy/mock): results = {grader_name: {score, passed}}

    Returns:
        Dict mapping grader_name to {"mean": float, "pass_rate": float, "count": int}.
    """
    from collections import defaultdict

    scores_by_grader: Dict[str, List[float]] = defaultdict(list)
    pass_by_grader: Dict[str, List[bool]] = defaultdict(list)

    for item in output_items:
        results = item.get("results", item.get("sample", {}))

        if isinstance(results, list):
            # Live API format: list of {name, score, passed, ...}
            for grader_result in results:
                if not isinstance(grader_result, dict):
                    continue
                grader_name = grader_result.get("name")
                if not grader_name:
                    continue
                score = grader_result.get("score")
                passed = grader_result.get("passed")
                if score is not None:
                    scores_by_grader[grader_name].append(float(score))
                if passed is not None:
                    pass_by_grader[grader_name].append(bool(passed))

        elif isinstance(results, dict):
            # Legacy/mock format: {grader_name: {score, passed}}
            for grader_name, grader_result in results.items():
                if isinstance(grader_result, dict):
                    score = grader_result.get("score")
                    passed = grader_result.get("passed")
                    if score is not None:
                        scores_by_grader[grader_name].append(float(score))
                    if passed is not None:
                        pass_by_grader[grader_name].append(bool(passed))

    summary: Dict[str, Dict[str, float]] = {}
    for name, scores in scores_by_grader.items():
        n = len(scores)
        mean = sum(scores) / n if n > 0 else 0.0
        passes = pass_by_grader.get(name, [])
        pass_rate = (sum(1 for p in passes if p) / len(passes) * 100) if passes else 0.0
        summary[name] = {"mean": round(mean, 3), "pass_rate": round(pass_rate, 1), "count": n}

    return summary


def _generate_markdown(
    result: EvalRunResult,
    config: CloudEvalConfig,
    output_path: Path,
) -> None:
    """Generate a Markdown summary report."""
    summary = _summarize_scores(result.output_items)
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    lines = [
        "# Foundry Cloud Evaluation Report",
        "",
        f"**Generated:** {now}",
        f"**Eval ID:** `{result.eval_id}`",
        f"**Run ID:** `{result.run_id}`",
        f"**Status:** {result.status}",
    ]

    if result.report_url:
        lines.append(f"**Portal:** [{result.report_url}]({result.report_url})")

    lines.extend(["", "---", "", "## Grader Results", ""])

    if summary:
        lines.append("| Grader | Mean Score | Pass Rate | Samples |")
        lines.append("|--------|-----------|-----------|---------|")
        for name, stats in sorted(summary.items()):
            lines.append(
                f"| {name} | {stats['mean']:.3f} | {stats['pass_rate']:.1f}% | {stats['count']} |"
            )
    else:
        lines.append("No grader results available.")

    # Result counts
    if result.result_counts:
        lines.extend(["", "## Result Counts", ""])
        for key, val in sorted(result.result_counts.items()):
            lines.append(f"- **{key}:** {val}")

    lines.extend(["", "---", "*Report generated by Foundry Evaluation SDK integration*", ""])

    output_path.write_text("\n".join(lines), encoding="utf-8")


def _extract_per_item_scores(output_items: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Extract per-item prompt_id + grader scores for cross-validation.

    Returns a list of dicts, each with prompt_id and per-grader score/passed.
    """
    items = []
    for item in output_items:
        prompt_id = None
        datasource = item.get("datasource_item")
        if isinstance(datasource, dict):
            prompt_id = datasource.get("prompt_id")

        scores: Dict[str, Any] = {}
        results = item.get("results", [])

        if isinstance(results, list):
            for grader in results:
                if isinstance(grader, dict) and grader.get("name"):
                    scores[grader["name"]] = {
                        "score": grader.get("score"),
                        "passed": grader.get("passed"),
                    }
        elif isinstance(results, dict):
            for name, val in results.items():
                if isinstance(val, dict):
                    scores[name] = {
                        "score": val.get("score"),
                        "passed": val.get("passed"),
                    }

        items.append({"prompt_id": prompt_id, "scores": scores})
    return items


def _generate_json(
    result: EvalRunResult,
    config: CloudEvalConfig,
    output_path: Path,
) -> None:
    """Generate a JSON results file with per-item scores for cross-validation."""
    summary = _summarize_scores(result.output_items)
    now = datetime.now(timezone.utc).isoformat()

    data = {
        "eval_id": result.eval_id,
        "run_id": result.run_id,
        "status": result.status,
        "report_url": result.report_url,
        "generated_at": now,
        "result_counts": result.result_counts,
        "grader_summary": summary,
        "output_items_count": len(result.output_items),
        "per_item_scores": _extract_per_item_scores(result.output_items),
    }

    output_path.write_text(
        json.dumps(data, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
